export function getLocalizedPackages(lang: Language) {
  const dict = translations[lang] || translations.en;
  return SIMULATOR_PACKAGES.map((pkg) => {
    if (pkg.id === 'pkg-discovery-30') {
      const basicLoc = BASIC_20_TRANSLATIONS[lang] || BASIC_20_TRANSLATIONS.en;
      return {
        ...pkg,
        ...basicLoc,
      };
    }
    if (pkg.id === 'pkg-promo-45') {
      const promoLoc = PROMO_45_TRANSLATIONS[lang] || PROMO_45_TRANSLATIONS.en;
      return {
        ...pkg,
        ...promoLoc,
      };
    }
    const loc = dict.packages[pkg.id as keyof typeof dict.packages];
    if (!loc) return pkg;
    return {
      ...pkg,
      title: loc.title,
      badge: loc.badge,
      shortDesc: loc.shortDesc,
      description: loc.description,
      features: loc.features,
    };
  });
}

export function getLocalizedAddons(lang: Language) {
  const dict = translations[lang] || translations.en;
  const missionLoc = MISSION_ADDONS_TRANSLATIONS[lang] || MISSION_ADDONS_TRANSLATIONS.en;
  return FLIGHT_ADDONS.map((addon) => {
    if (missionLoc[addon.id]) {
      return {
        ...addon,
        name: missionLoc[addon.id].name,
        description: missionLoc[addon.id].description,
      };
    }
    const loc = dict.addons[addon.id as keyof typeof dict.addons];
    if (!loc) return addon;
    return {
      ...addon,
      name: loc.name,
      description: loc.description,
    };
  });
}
