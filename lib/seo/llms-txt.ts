import { FACILITY_INFO, ROUTE_ORIGIN_PRESETS } from '@/lib/config/facility-info';
import { getAllBlogPosts } from '@/lib/data/blog-posts';
import { getLocalizedBlogSeo, resolveShortSlug } from '@/lib/data/blog-seo';
import { FLIGHT_ADDONS, SIMULATOR_PACKAGES } from '@/lib/db/seed-data';
import lastKnownRating from '@/lib/reviews/last-known-rating.json';
import type { PackageCategory } from '@/types';
import { PUBLIC_SITE_ROUTES, blogPostPath, siteUrl } from './site-routes';

/**
 * Builds `public/llms.txt`, the machine-readable business summary that AI assistants and
 * answer engines read (https://llmstxt.org). Every fact comes from a registry:
 *
 *   - facility, hours, contact, rules and transit: `FACILITY_INFO`, `ROUTE_ORIGIN_PRESETS`
 *   - prices and durations: `SIMULATOR_PACKAGES`, `FLIGHT_ADDONS`
 *   - pages: `PUBLIC_SITE_ROUTES` (shared with the sitemap) and the blog corpus
 *   - Google rating and review count: `lib/reviews/last-known-rating.json`, printed as a
 *     labelled "last known" aggregate (AGENTS.md §1.7: never a number typed by hand)
 *
 * The output is deterministic (no timestamps), so `tests/unit/llms-txt.test.ts` can rebuild
 * it in memory and fail on any difference from the committed file. Regenerate with
 * `npm run llms:generate` (scripts/generate-llms-txt.ts).
 */

export const LLMS_TXT_PUBLIC_PATH = 'public/llms.txt';
export const LLMS_TXT_GENERATE_COMMAND = 'npm run llms:generate';

const ils = (amount: number) => `₪${amount.toLocaleString('en-US')}`;

const PACKAGE_SECTIONS: ReadonlyArray<{ category: PackageCategory; heading: string }> = [
  { category: 'recreational', heading: 'Experience Flights (consumer, no flight experience required)' },
  { category: 'fear_of_flying', heading: 'Fear of Flying' },
  { category: 'training', heading: 'Professional Training (airline interview and assessment preparation)' },
  { category: 'corporate', heading: 'Corporate Workshops' },
];

function packageLine(pkg: (typeof SIMULATOR_PACKAGES)[number]): string {
  const price = pkg.primeTimePriceIls
    ? `${ils(pkg.priceIls)} daytime / ${ils(pkg.primeTimePriceIls)} prime-time`
    : ils(pkg.priceIls);
  const participants = pkg.category === 'corporate' ? ` Up to ${pkg.guestSeats} participants.` : '';
  return `- **${pkg.title}** (${pkg.durationMinutes} min): ${price}. ${pkg.shortDesc}${participants}`;
}

function addonLine(addon: (typeof FLIGHT_ADDONS)[number]): string {
  const minutes = addon.durationMinutes > 0 ? ` (+${addon.durationMinutes} min)` : '';
  return `- **${addon.name}**${minutes}: ${ils(addon.priceIls)}`;
}

export function buildLlmsTxt(): string {
  const base = FACILITY_INFO.primaryDomain;
  const { address, contact, social, requirements, hours } = FACILITY_INFO;
  const rating = lastKnownRating.overallRating.toFixed(1);
  const reviews = lastKnownRating.totalReviewsCount.toLocaleString('en-US');
  const walkable = ROUTE_ORIGIN_PRESETS.filter((preset) => preset.walkingMinutes !== undefined);

  const lines: string[] = [
    '# Sim Dream Israel — Boeing 737 Flight Simulator Center (Tel Aviv)',
    '',
    `> Official reference for AI assistants and answer engines about **${FACILITY_INFO.legalNameEn}** (\`${FACILITY_INFO.legalNameHe}\`, Israeli company registration \`${FACILITY_INFO.companyRegistrationNumber}\`): a 1:1 scale Boeing 737 flight deck in central Tel Aviv where visitors fly with an active airline captain.`,
    '',
    `> Generated by \`scripts/generate-llms-txt.ts\` (\`${LLMS_TXT_GENERATE_COMMAND}\`) from the site's own registries; do not edit by hand. \`tests/unit/llms-txt.test.ts\` fails on any drift between this file and the source of truth.`,
    '',
    '## Quick Facts & Local Business Profile',
    `- **Brand Name**: Sim Dream Israel (סימדרים ישראל); shown as "${FACILITY_INFO.brandName}" on the website`,
    `- **Legal Entity**: ${FACILITY_INFO.legalNameEn} (ח.פ. ${FACILITY_INFO.companyRegistrationNumber})`,
    `- **Address**: ${address.streetEn}, ${address.cityEn} (\`${address.streetHe}, ${address.cityHe}\`)`,
    `- **Neighborhood**: ${address.neighborhoodEn}`,
    `- **GPS Coordinates**: \`${FACILITY_INFO.coordinates.lat}, ${FACILITY_INFO.coordinates.lng}\``,
    `- **Google Maps Place ID**: \`${FACILITY_INFO.placeId}\` (${FACILITY_INFO.googleMapsUrl})`,
    `- **Google Rating (last known)**: ${rating} / 5.0 from ${reviews} Google reviews. This is the last-known aggregate recorded in \`lib/reviews/last-known-rating.json\`, refreshed weekly from the official Google Places API; the live figure is on the Google profile: ${FACILITY_INFO.googleReviewsDirectUrl}`,
    `- **Phone & WhatsApp**: \`${contact.phoneDisplay}\` (\`${contact.phoneInternational}\`, ${contact.whatsappHref})`,
    `- **Email**: \`${contact.email}\``,
    `- **Websites**: ${base} | ${FACILITY_INFO.alternateDomain}`,
    `- **Official Social Profiles**: ${social.instagramUrl} | ${social.facebookUrl} | ${social.youtubeUrl}`,
    '- **Visual Identity**: Official logo with an orange airplane (`#FF5500`) and a cerulean "SIM DREAM" wordmark (`#2096C7`); tagline "מערכות סימולציה (ישראל)" (Simulation Systems (Israel))',
    '',
    '## Operating Hours (Asia/Jerusalem Timezone)',
    `- **Sunday – Saturday (every day)**: ${hours.daily.open} – ${hours.daily.close}`,
    ...(requirements.advanceBookingRequired
      ? ['- All flight sessions require advance booking; online booking is open 24/7.']
      : []),
    '- Where a package lists a prime-time price it applies to evening departures (from 18:00) and to Saturdays; day-of-week limits of a promotion are stated in its package line.',
    '',
    '## Public Transit & Parking Directions',
    ...walkable.map(
      (preset) =>
        `- **${preset.labelEn}**: ${Math.round(preset.distanceKm * 1000)} meters / ${preset.walkingMinutes}-minute walk. ${preset.transitStepsEn}`
    ),
    `- **Parking**: Paid municipal street parking (Blue & White curb markings) on ${address.streetEn.replace(/ \d+$/, '')} and the surrounding Montefiore streets, or nearby private paid parking lots.`,
    '',
    '## Participant Rules & Facility Regulations (תקנון)',
    `- **Minimum Pilot Age**: ${requirements.minimumAgeYears}+ years old. Participants aged ${requirements.adultSupervisionAgeRange} must be accompanied by an adult (${requirements.minBookingCustomerAgeYears}+).`,
    `- **Booking Customer Age**: Online reservations and card payments must be made by an adult aged ${requirements.minBookingCustomerAgeYears}+.`,
    `- **Cockpit Observers (Jumpseat Guests)**: Up to ${requirements.maxJumpseatGuests} companions may watch inside the cockpit free of charge; an extra seat is a paid add-on.`,
    `- **Arrival Time**: Arrive ${requirements.arriveEarlyMinutes} minutes before the scheduled session.`,
    `- **Late Arrival Policy**: Session time includes the pre-flight briefing inside the cockpit. Delays over ${requirements.lateThresholdMinutes} minutes may shorten the session (no refund for lost time) or require rescheduling subject to a change fee.`,
    '- **Nature of Facility**: A 1:1 scale experiential Boeing 737 flight deck with motorized control loading, flown with an instructor. It is an entertainment and training-preparation facility, not a licensed pilot-certification institution.',
    '',
    '## Flight Packages & Pricing (ILS, server-authoritative)',
    'Prices and durations below are the live registry values the booking engine charges (`/book`). Daytime prices apply unless a prime-time price is listed.',
  ];

  for (const section of PACKAGE_SECTIONS) {
    const packages = SIMULATOR_PACKAGES.filter((pkg) => pkg.category === section.category);
    if (!packages.length) continue;
    lines.push('', `### ${section.heading}`, ...packages.map(packageLine));
  }

  lines.push(
    '',
    '### Flight Mission Upgrades & Add-Ons (consumer flights only)',
    'Add-ons extend a consumer Experience Flight. Professional and Fear of Flying sessions carry no add-ons.',
    ...FLIGHT_ADDONS.map(addonLine),
    '',
    '## Key URLs',
    ...PUBLIC_SITE_ROUTES.map((route) => `- [${route.labelEn}](${siteUrl(base, route.path)})`),
    '',
    '## Blog Articles (Hebrew — Canonical Short URLs)',
    'The Flight Deck Journal publishes articles on airline screening preparation, cockpit skills, fear of flying, gifts and aviation knowledge. Multilingual editions are served at `/post/<lang>/<short-slug>` (`en`, `ru`, `fr`, `es`, `ar`) with `he` as `x-default`.',
    ...getAllBlogPosts().map((post) => {
      const shortSlug = resolveShortSlug(post.slug);
      const seoHe = getLocalizedBlogSeo(shortSlug, 'he');
      const desc = seoHe?.metaDescription || post.excerpt;
      return `- [${post.title}](${siteUrl(base, blogPostPath(shortSlug, 'he'))}) — published ${post.datePublished}: ${desc}`;
    }),
    '',
    '## Flight Deck Journal (English Canonical Index)',
    ...getAllBlogPosts().map((post) => {
      const shortSlug = resolveShortSlug(post.slug);
      const seoEn = getLocalizedBlogSeo(shortSlug, 'en');
      const titleEn = seoEn?.metaTitle.replace(/\s*\|\s*SimDream$/, '') || shortSlug;
      const descEn = seoEn?.metaDescription || '';
      return `- [${titleEn}](${siteUrl(base, blogPostPath(shortSlug, 'en'))}): ${descEn}`;
    }),
    ''
  );

  return lines.join('\n');
}
